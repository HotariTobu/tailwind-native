#!/usr/bin/env python3
"""Generate native numeric token scales from the vendored Tailwind theme."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
css = (ROOT/'tokens/theme.css').read_text()
spacing_unit = float(re.search(r'--spacing: ([\d.]+)rem;', css).group(1)) * 16

def values(prefix, unit=''):
    return {name: float(value) * (16 if unit == 'rem' else 1)
            for name, value in re.findall(r'--' + prefix + r'-([\w-]+): (-?[\d.]+)' + unit + ';', css)}

scales = {
    'Radius': {'none': 0, **values('radius', 'rem'), 'full': 9999},
    'TextSize': values('text', 'rem'),
    'Weight': values('font-weight'),
    'Tracking': values('tracking', 'em'),
    'Leading': values('leading'),
    'Container': values('container', 'rem'),
    'Breakpoint': values('breakpoint', 'rem'),
    'Blur': {'none': 0, **values('blur', 'px')},
}
line_heights = {}
for name, value in re.findall(r'--text-([\w]+)--line-height: ([^;]+);', css):
    if value.startswith('calc('):
        numerator, denominator = map(float, value[5:-1].split('/'))
        line_heights[name] = scales['TextSize'][name] * numerator / denominator
    else:
        line_heights[name] = scales['TextSize'][name] * float(value)
assert len(scales['Radius']) == 10
assert len(line_heights) == 13
shadows = {'none': []}
for name, value in re.findall(r'--shadow-([\w-]+): ([^;]+);', css):
    if 'inset' in value:  # Deprecated shadow-inner is not an outer box shadow.
        continue
    layers = []
    for layer in value.split(','):
        geometry, color = layer.split('rgb(')
        numbers = list(map(float, re.findall(r'-?[\d.]+', geometry)))
        numbers += [0.0] * (4 - len(numbers))
        opacity = float(re.search(r'/ ([\d.]+)', color).group(1))
        layers.append(dict(zip(['x', 'y', 'blur', 'spread', 'opacity'], [*numbers, opacity])))
    shadows[name] = layers
assert len(shadows) == 8
(ROOT/'tokens/scales.json').write_text(json.dumps({**scales, 'SpacingUnit': spacing_unit, 'TextLineHeight': line_heights, 'Shadow': shadows}, indent=2)+'\n')

names = {'2xl':'xxl', '3xl':'xxxl', '4xl':'x4l', '5xl':'x5l', '6xl':'x6l', '7xl':'x7l',
         '8xl':'x8l', '9xl':'x9l', '2xs':'xxs', '3xs':'xxxs'}
def swift_name(name):
    return '`' + name + '`' if name == 'normal' else names.get(name, name)
def kotlin_name(name):
    return names.get(name, name).capitalize()

def number(value):
    return str(int(value)) if value.is_integer() else str(value)

swift = ['// Generated by tools/generate_tokens.py. Do not edit.', 'import SwiftUI', '', 'public extension TW {', f'    static let spacingUnit: Double = {number(spacing_unit)}']
kotlin = ['// Generated by tools/generate_tokens.py. Do not edit.', 'package dev.tailwind.nativeui', '',
          'import androidx.compose.ui.text.font.FontWeight', 'import androidx.compose.ui.unit.sp',
          'import androidx.compose.ui.unit.dp', '', 'object TW {',
          f'    const val spacingUnit: Double = {spacing_unit}', '''    fun spacing(value: Number): androidx.compose.ui.unit.Dp {
        require(value.toDouble() >= 0) { "Spacing must be nonnegative" }
        return signedSpacing(value)
    }
    fun signedSpacing(value: Number): androidx.compose.ui.unit.Dp {
        val points = finiteNumber(value) * spacingUnit
        return nativeFloat(points).dp
    }''']
weight_map = ['ultraLight','thin','light','regular','medium','semibold','bold','heavy','black']
for family, entries in scales.items():
    swift += [f'    enum {family}: Double, CaseIterable, Sendable {{']
    for name, value in entries.items():
        swift += [f'        case {swift_name(name)} = {number(float(value))}']
    if family == 'Weight':
        swift += ['        public var native: Font.Weight {', '            switch self {']
        swift += [f'            case .{swift_name(name)}: .{native}' for name, native in zip(entries, weight_map)]
        swift += ['            }', '        }']
    if family == 'TextSize':
        swift += ['        public var lineHeight: Double {', '            switch self {']
        swift += [f'            case .{swift_name(name)}: {number(float(line_heights[name]))}' for name in entries]
        swift += ['            }', '        }']
    if family == 'Breakpoint':
        swift += ['        public func matches(width: Double) -> Bool { width >= rawValue }']
    swift += ['    }']
    prop = 'em' if family in ('Tracking', 'Leading') else 'points'
    kind = 'Float' if family in ('Tracking','Leading') else 'Int'
    kotlin += [f'    enum class {family}(val {prop}: {kind}) {{']
    for index, (name, value) in enumerate(entries.items()):
        literal = number(float(value)) + ('f' if kind == 'Float' else '')
        kotlin += [f'        {kotlin_name(name)}({literal})' + (';' if index == len(entries)-1 else ',')]
    if family == 'Weight':
        kotlin += ['        val native get() = FontWeight(points)']
    if family == 'TextSize':
        kotlin += ['        val native get() = points.sp', '        val lineHeight: Int get() = when (this) {']
        kotlin += [f'            {kotlin_name(name)} -> {number(float(line_heights[name]))}' for name in entries]
        kotlin += ['        }']
    if family == 'Breakpoint':
        kotlin += ['        fun matches(width: Float) = width >= points']
    kotlin += ['    }']
swift += ['''    struct ShadowLayer: Sendable, Equatable {
        public let x, y, blur, spread, opacity: Double
        public init(x: Double, y: Double, blur: Double, spread: Double, opacity: Double) {
            precondition([x, y, blur, spread, opacity].allSatisfy { $0.isFinite } && blur >= 0 && (0...1).contains(opacity), "Invalid shadow layer")
            self.x = x; self.y = y; self.blur = blur; self.spread = spread; self.opacity = opacity
        }
    }''', '    enum Shadow: CaseIterable, Sendable {']
swift += ['        case ' + ', '.join(swift_name(name) for name in shadows)]
swift += ['        public var layers: [ShadowLayer] {', '            switch self {']
for name, layers in shadows.items():
    literals = [".init(" + ', '.join(key + ': ' + number(value) for key, value in layer.items()) + ')' for layer in layers]
    swift += [f"            case .{swift_name(name)}: [" + ', '.join(literals) + ']']
swift += ['            }', '        }',
          '        public var radius: Double { (layers.first?.blur ?? 0) / 2 }',
          '        public var y: Double { layers.first?.y ?? 0 }', '    }', '}']
kotlin += ['''    data class ShadowLayer(val x: Float, val y: Float, val blur: Float, val spread: Float, val opacity: Float) {
        init {
            require(listOf(x, y, blur, spread, opacity).all { it.isFinite() } && blur >= 0 && opacity in 0f..1f) { "Invalid shadow layer" }
        }
    }''', '    enum class Shadow(val layers: List<ShadowLayer>) {']
for index, (name, layers) in enumerate(shadows.items()):
    literals = ['ShadowLayer(' + ', '.join(number(value) + 'f' for value in layer.values()) + ')' for layer in layers]
    kotlin += [f"        {kotlin_name(name)}(listOf(" + ', '.join(literals) + '))' + (';' if index == len(shadows)-1 else ',')]
kotlin += ['    }', '}', '', 'typealias Breakpoint = TW.Breakpoint']
(ROOT/'swiftui/Sources/swiftui/ThemeTokens.swift').write_text('\n'.join(swift)+'\n')
(ROOT/'jetpackcompose/src/main/kotlin/dev/tailwind/nativeui/Tokens.kt').write_text('\n'.join(kotlin)+'\n')
