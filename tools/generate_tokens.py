#!/usr/bin/env python3
"""Generate matching sRGB palettes from the pinned Tailwind v4.3.3 theme.

Out-of-sRGB OKLCH components are clipped after conversion. No network required.
"""
from pathlib import Path
import math
import re
import json

ROOT = Path(__file__).resolve().parents[1]

def srgb(v):
    return min(1, max(0, 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1/2.4) - 0.055))

def convert(lightness, chroma, hue):
    a, b = chroma * math.cos(math.radians(hue)), chroma * math.sin(math.radians(hue))
    l = (lightness + 0.3963377774*a + 0.2158037573*b) ** 3
    m = (lightness - 0.1055613458*a - 0.0638541728*b) ** 3
    s = (lightness - 0.0894841775*a - 1.2914855480*b) ** 3
    return [round(srgb(v)*255) for v in (
        4.0767416621*l - 3.3077115913*m + 0.2309699292*s,
        -1.2684380046*l + 2.6097574011*m - 0.3413193965*s,
        -0.0041960863*l - 0.7034186147*m + 1.7076147010*s)]

colors = {}
for name, lightness, chroma, hue in re.findall(
    r'--color-([\w-]+): oklch\(([\d.]+)% ([\d.]+) (none|[\d.]+)\)',
    (ROOT / 'tokens/theme.css').read_text()):
    if hue == 'none':
        assert float(chroma) == 0, f"Missing hue in chromatic color: {name}"
    colors[name] = convert(float(lightness)/100, float(chroma), 0 if hue == 'none' else float(hue))
assert len(colors) == 286
colors.update(black=[0,0,0], white=[255,255,255])
(ROOT/'tokens/colors.json').write_text(json.dumps(colors, indent=2)+'\n')
swift = ['// Generated by tools/generate_tokens.py. Do not edit.', 'import SwiftUI', '', 'public extension TW {', '    enum Palette {']
kotlin = ['// Generated by tools/generate_tokens.py. Do not edit.', 'package dev.tailwind.nativeui', '', 'import androidx.compose.ui.graphics.Color', '', 'object Palette {']
for name, rgb in colors.items():
    identifier = name.replace('-', '')
    swift.append(f'        public static let {identifier} = Color(.sRGB, red: {rgb[0]}/255.0, green: {rgb[1]}/255.0, blue: {rgb[2]}/255.0, opacity: 1)')
    kotlin.append(f'    val {identifier} = Color(0xFF{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X})')
swift += ['        public static let transparent = Color.clear', '    }', '}']
kotlin += ['    val transparent = Color.Transparent', '}']
(ROOT/'swiftui/Sources/swiftui/Palette.swift').write_text('\n'.join(swift)+'\n')
(ROOT/'jetpackcompose/src/main/kotlin/dev/tailwind/nativeui/Palette.kt').write_text('\n'.join(kotlin)+'\n')

# Keep all non-color token scales derived from the same pinned source.
import runpy
runpy.run_path(str(ROOT/'tools/generate_theme_tokens.py'))
